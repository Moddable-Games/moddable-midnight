// Regenerates the crew Worker's game tables from Midnight City's public content dump.
//
//   node scripts/build-city-tables.mjs [contentVersion]
//
// The version defaults to the one the Worker last saw (its status JSON). Writes:
//   worker/src/recipes.js    every recipe, and every gathering source by output item
//   worker/src/contracts.js  every contract, with its reward items
//
// The tables used to hold only the recipes on the way to a tool, so the planner could
// source 18 of the 68 items that low-level contracts ask for. With the full dump it can
// plan every contract whose items are gathered or crafted (rare drops are left out: they
// are chances, not plans).
import { writeFileSync } from "node:fs";

const OBSERVER = "https://midnight.city/observer";
const STATUS = "https://midnight-city-crew.neuroware.workers.dev/";
const OUT = new URL("../worker/src/", import.meta.url).pathname;

const version = process.argv[2] ?? (await (await fetch(STATUS)).json()).contentVersion;
if (!version) throw new Error("no content version given and none in the Worker status");
const dump = await (await fetch(`${OBSERVER}/api/static-world/${version}`)).json();
const game = dump.staticWorld.gameContent;

const byId = (list) => [...list].sort((a, b) => a.id.localeCompare(b.id));
const pairs = (list) => Object.fromEntries(list.map((x) => [x.itemId, x.quantity]));
const js = (value) => JSON.stringify(value).replace(/"([a-zA-Z_][a-zA-Z0-9_]*)":/g, "$1: ");

// Recipes, and gathering sources indexed by the items they give every time.
const recipeLines = byId(game.recipes).map((r) =>
  `  ${r.id}: { skill: "${r.skill}", level: ${r.requiredLevel}, inputs: ${js(pairs(r.inputs))}, outputs: ${js(pairs(r.outputs))} },`);
const sourcesByItem = {};
for (const source of byId(game.sources)) {
  for (const output of source.outputs) {
    (sourcesByItem[output.itemId] ??= []).push({ sourceId: source.id, skill: source.skill, level: source.requiredLevel });
  }
}
const sourceLines = Object.keys(sourcesByItem).sort().map((item) => `  ${item}: ${js(sourcesByItem[item])},`);

writeFileSync(OUT + "recipes.js", `// Every recipe, and every gathering source by the items it always gives, from the Midnight
// City content dump (version ${version.slice(0, 12)}…). Generated by scripts/build-city-tables.mjs;
// do not edit by hand. The progression API lists only recipes craftable right now, so plans
// use this table. Crafting walks the agent to the right workstation on its own.
export const RECIPES = {
${recipeLines.join("\n")}
};

// Normal outputs only. Rare outputs are chances, so the planner never counts on them.
export const SOURCES_BY_ITEM = {
${sourceLines.join("\n")}
};
`);

// Contracts, with the non-crystal rewards that other contracts may ask for.
const contractLines = byId(game.contracts).map((c) => {
  const crystal = c.rewards.find((r) => r.itemId === "crystal")?.quantity ?? 0;
  const rewards = c.rewards.filter((r) => r.itemId !== "crystal").map((r) => r.itemId);
  return `  "${c.id}": { area: "${c.areaId}", skill: "${c.skill}", level: ${c.requiredLevel}, xp: ${c.xp}, crystal: ${crystal}, rewards: ${JSON.stringify(rewards)}, requirements: ${js(c.requirements)} },`;
});
writeFileSync(OUT + "contracts.js", `// Contracts from the Midnight City content dump (version ${version.slice(0, 12)}…). Generated by
// scripts/build-city-tables.mjs; do not edit by hand. The progression API lists a contract as
// open only once the agent already holds the goods, so plans come from here (FINDINGS 20, 22).
// One-time each: completedContractIds in progression says which are spent.
// \`area\` matters: deliver_contract does NOT walk the agent there (FINDINGS 23).
export const CONTRACTS = {
${contractLines.join("\n")}
};
`);

console.log(`version ${version.slice(0, 12)}…: ${game.recipes.length} recipes, ${Object.keys(sourcesByItem).length} gatherable items from ${game.sources.length} sources, ${game.contracts.length} contracts`);
